"""Pruebas estáticas de esquema y catálogo que no requieren Flask."""
import ast
import re
import sqlite3
import unittest
from pathlib import Path

APP = Path(__file__).resolve().parents[1] / 'app.py'
TREE = ast.parse(APP.read_text(encoding='utf-8'))
VALUES = {}
for node in TREE.body:
    if isinstance(node, ast.Assign):
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id in {'SCHEMA', 'PLACES'}:
                VALUES[target.id] = ast.literal_eval(node.value)


class SchemaTests(unittest.TestCase):
    def test_catalog_has_twelve_curated_places(self):
        self.assertEqual(len(VALUES['PLACES']), 12)
        self.assertTrue(all(len(place) == 15 for place in VALUES['PLACES']))
        self.assertTrue(all(place[7].startswith('https://upload.wikimedia.org/') for place in VALUES['PLACES']))
        self.assertTrue(all(place[12] and place[13] and place[14] for place in VALUES['PLACES']))

    def test_sqlite_schema_and_seed(self):
        db = sqlite3.connect(':memory:')
        db.execute('PRAGMA foreign_keys=ON')
        db.executescript(VALUES['SCHEMA'])
        db.executemany(
            'INSERT INTO lugar (id_lugar,ciudad,nombre,categoria,etiquetas,lat,lon,imagen,precio_estimado,duracion_min,interior,descripcion,credito,licencia,fuente) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
            VALUES['PLACES'])
        count = db.execute('SELECT COUNT(*) FROM lugar').fetchone()[0]
        self.assertEqual(count, 12)
        self.assertTrue(db.execute('PRAGMA foreign_key_check').fetchall() == [])

    def test_postgres_schema_conversion(self):
        schema = VALUES['SCHEMA'].replace('PRAGMA foreign_keys=ON;', '')
        schema = schema.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        schema = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', schema)
        self.assertNotIn('AUTOINCREMENT', schema)
        self.assertNotIn('PRAGMA', schema)
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', schema)
        self.assertIn('DOUBLE PRECISION', schema)


if __name__ == '__main__':
    unittest.main(verbosity=2)
