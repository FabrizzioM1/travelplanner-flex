"""Planificador 3.0: gastos previstos por día, aportantes y PDF.

Migración estrictamente aditiva. Reutiliza actividad, hospedaje, transporte, gasto y viaje.
"""
from __future__ import annotations
from datetime import date, timedelta
from decimal import Decimal, InvalidOperation
from io import BytesIO
from html import escape as html_escape
from flask import jsonify, request, send_file

TYPE_LABELS = {
    'desayuno':'Desayuno', 'comida':'Comida', 'cena':'Cena',
    'boleto_ida':'Boletos de ida', 'boleto_regreso':'Boletos de regreso',
    'uber':'Uber / taxi', 'renta_auto':'Renta de automóvil',
    'gasolina':'Gasolina', 'casetas':'Casetas', 'estacionamiento':'Estacionamiento',
    'traslado':'Traslado local', 'otro':'Otro gasto previsto',
}
FOOD_TYPES = ('desayuno','comida','cena')
TRAVEL_TYPES = ('boleto_ida','boleto_regreso','uber','renta_auto','gasolina','casetas','estacionamiento','traslado')
DEFAULT_MEALS = (('desayuno',100),('comida',180),('cena',140))


def create_plan_schema(db):
    # SQLite y PostgreSQL: PK autoincremental compatible sin tocar tablas antiguas.
    pg = hasattr(db, 'conn') and db.__class__.__name__ == 'PostgresCompat'
    ident = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if pg else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    db.execute(f'''CREATE TABLE IF NOT EXISTS plan_concepto (
      id_concepto {ident},
      id_viaje INTEGER NOT NULL REFERENCES viaje(id_viaje) ON DELETE CASCADE,
      fecha TEXT NOT NULL,
      tipo TEXT NOT NULL,
      nombre TEXT NOT NULL,
      hora TEXT NOT NULL DEFAULT '',
      precio_unitario DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(precio_unitario >= 0),
      cantidad DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK(cantidad > 0),
      personas INTEGER NOT NULL DEFAULT 1 CHECK(personas >= 1),
      incluido INTEGER NOT NULL DEFAULT 0 CHECK(incluido IN (0,1)),
      automatico INTEGER NOT NULL DEFAULT 0 CHECK(automatico IN (0,1)),
      nota TEXT NOT NULL DEFAULT ''
    )''')
    db.execute('''CREATE TABLE IF NOT EXISTS plan_configuracion (
      id_viaje INTEGER PRIMARY KEY REFERENCES viaje(id_viaje) ON DELETE CASCADE,
      pagadores INTEGER NOT NULL DEFAULT 1 CHECK(pagadores >= 1),
      reserva_pct DOUBLE PRECISION NOT NULL DEFAULT 15 CHECK(reserva_pct >= 0 AND reserva_pct <= 50)
    )''')
    db.execute('CREATE INDEX IF NOT EXISTS idx_plan_concepto_viaje_fecha ON plan_concepto(id_viaje, fecha)')


def money_value(v):
    try:
        n=Decimal(str(v))
        if not n.is_finite() or n < 0 or n > Decimal('100000000'): raise ValueError()
        return float(n.quantize(Decimal('.01')))
    except (ValueError, InvalidOperation, TypeError):
        raise ValueError('El importe debe ser un número entre 0 y 100,000,000.')


def ensure_trip_plan(db, trip_info):
    """Se ejecuta varias veces sin duplicar días o comidas automáticas."""
    tid=int(trip_info['id_viaje'])
    first=date.fromisoformat(trip_info['fecha_inicio']); last=date.fromisoformat(trip_info['fecha_fin'])
    duration=(last-first).days+1
    if duration>60: # No creamos 180 comidas masivas en viajes muy largos.
        raise ValueError('El planificador admite viajes de hasta 60 días.')
    exists=db.execute('SELECT id_viaje FROM plan_configuracion WHERE id_viaje=?',(tid,)).fetchone()
    if not exists:
        db.execute('INSERT INTO plan_configuracion(id_viaje,pagadores,reserva_pct) VALUES (?,?,?)',
                   (tid, max(1,int(trip_info['num_viajeros'])), 15))
    for offset in range(duration):
        today=(first+timedelta(days=offset)).isoformat()
        db.execute('INSERT INTO itinerario(id_viaje,fecha,titulo,descripcion) VALUES (?,?,?,?) ON CONFLICT(id_viaje,fecha) DO NOTHING',
                   (tid,today,f'Día {offset+1}',''))
        for tipo, precio in DEFAULT_MEALS:
            if not db.execute('SELECT id_concepto FROM plan_concepto WHERE id_viaje=? AND fecha=? AND tipo=? AND automatico=1',
                              (tid,today,tipo)).fetchone():
                db.execute('''INSERT INTO plan_concepto(id_viaje,fecha,tipo,nombre,precio_unitario,cantidad,personas,automatico,nota)
                              VALUES (?,?,?,?,?,?,?,?,?)''',
                           (tid,today,tipo,TYPE_LABELS[tipo],precio,1,int(trip_info['num_viajeros']),1,
                            'Referencia editable por persona, NO precio verificado.'))


def calculated_plan(db, trip_info, rows):
    ensure_trip_plan(db,trip_info)
    tid=trip_info['id_viaje']
    items=rows(db,'SELECT * FROM plan_concepto WHERE id_viaje=? ORDER BY fecha,hora,id_concepto',(tid,))
    days=rows(db,'SELECT * FROM itinerario WHERE id_viaje=? ORDER BY fecha',(tid,))
    hotels=rows(db,'SELECT * FROM hospedaje WHERE id_viaje=? ORDER BY fecha_entrada',(tid,))
    transports=rows(db,'SELECT * FROM transporte WHERE id_viaje=? ORDER BY fecha_hora_salida',(tid,))
    activities=rows(db,"""SELECT a.*,i.fecha FROM actividad a JOIN itinerario i ON i.id_itinerario=a.id_itinerario
                      WHERE i.id_viaje=? AND a.estado!='cancelada' ORDER BY i.fecha,a.hora_inicio""",(tid,))
    # Real spending stays separate: planned cost is not a payment.
    real=db.execute('SELECT COALESCE(SUM(monto),0) FROM gasto WHERE id_viaje=?',(tid,)).fetchone()[0]
    cfg=rows(db,'SELECT * FROM plan_configuracion WHERE id_viaje=?',(tid,))[0]
    categories={'alimentacion':0., 'ida_y_regreso':0., 'transporte_local':0., 'hospedaje':0., 'actividades':0., 'otros':0.}
    daily={d['fecha']: {'fecha':d['fecha'],'id_itinerario':d['id_itinerario'], 'titulo':d['titulo'],
                        'conceptos':[], 'actividades':[], 'hospedajes':[], 'transportes':[], 'subtotal':0.0}
           for d in days}
    def add_daily(fecha, category, amount):
        categories[category]+=amount
        if fecha in daily: daily[fecha]['subtotal']+=amount
    for it in items:
        total=0. if it['incluido'] else round(float(it['precio_unitario'])*float(it['cantidad'])*int(it['personas']),2)
        it['total']=total
        if it['tipo'] in FOOD_TYPES: category='alimentacion'
        elif it['tipo'] in ('boleto_ida','boleto_regreso'): category='ida_y_regreso'
        elif it['tipo'] in TRAVEL_TYPES: category='transporte_local'
        else: category='otros'
        add_daily(it['fecha'],category,total)
        if it['fecha'] in daily: daily[it['fecha']]['conceptos'].append(it)
    for a in activities:
        total=float(a['costo_estimado'] or 0)
        add_daily(a['fecha'],'actividades',total)
        if a['fecha'] in daily: daily[a['fecha']]['actividades'].append(a)
    for h in hotels:
        total=float(h['costo'] or 0)
        # Entire reservation priced only once (not on every night).
        add_daily(h['fecha_entrada'],'hospedaje',total)
        if h['fecha_entrada'] in daily: daily[h['fecha_entrada']]['hospedajes'].append(h)
    for tr in transports:
        total=float(tr['costo'] or 0)
        firstday=tr['fecha_hora_salida'][:10]
        add_daily(firstday,'ida_y_regreso',total)
        if firstday in daily: daily[firstday]['transportes'].append(tr)
    subtotal=round(sum(categories.values()),2)
    recommended=round(subtotal*(1+float(cfg['reserva_pct'])/100),2)
    payers=min(int(cfg['pagadores']),max(1,int(trip_info['num_viajeros'])))
    return {'viaje':trip_info,'dias':list(daily.values()),'config':cfg,
            'categorias':{k:round(v,2) for k,v in categories.items()},
            'subtotal':subtotal,'fondo_imprevistos':round(recommended-subtotal,2),
            'total_recomendado':recommended,'pagadores':payers,
            'aporte_por_pagador':round(recommended/payers,2),'gastado_real':round(float(real or 0),2),
            'aviso':'Importes ilustrativos y editables; verifica precios reales. Los gastos pagados se muestran por separado.'}


def register_planner(app,connect,trip,rows,UserError):
    def need_trip(db,tid):
        t=trip(db,int(tid))
        return t
    def get_plan(db,tid):
        t=need_trip(db,tid)
        try: return calculated_plan(db,t,rows)
        except ValueError as err: raise UserError(str(err))
    def validate_concept(db,tid,p,old=None):
        t=need_trip(db,tid)
        typ=str(p.get('tipo',old['tipo'] if old else '')).strip()
        if typ not in TYPE_LABELS: raise UserError('Tipo de concepto no permitido.')
        fecha=str(p.get('fecha',old['fecha'] if old else ''))
        if fecha<t['fecha_inicio'] or fecha>t['fecha_fin']:
            raise UserError('Selecciona un día dentro de las fechas del viaje.')
        try: date.fromisoformat(fecha)
        except ValueError: raise UserError('Fecha incorrecta.')
        name=str(p.get('nombre',old['nombre'] if old else TYPE_LABELS[typ])).strip()
        if not name or len(name)>140: raise UserError('Nombre requerido (hasta 140 caracteres).')
        hora=str(p.get('hora',old['hora'] if old else ''))[:5]
        if hora:
            try:
                from datetime import time
                time.fromisoformat(hora)
            except ValueError: raise UserError('Hora incorrecta.')
        try:
            unit=money_value(p.get('precio_unitario',old['precio_unitario'] if old else 0))
            quantity=float(p.get('cantidad',old['cantidad'] if old else 1))
            people=int(p.get('personas',old['personas'] if old else 1))
            if not (0<quantity<=365) or not (1<=people<=int(t['num_viajeros'])): raise ValueError()
        except (ValueError,TypeError): raise UserError('Revisa cantidad y número de personas.')
        included=int(str(p.get('incluido',old['incluido'] if old else 0)) in ('1','true','True'))
        note=str(p.get('nota',old['nota'] if old else ''))[:350]
        return (fecha,typ,name,hora,unit,quantity,people,included,note)

    @app.get('/api/viajes/<int:tid>/plan')
    def api_plan(tid):
        with connect() as db: return jsonify(get_plan(db,tid))

    @app.post('/api/viajes/<int:tid>/plan/conceptos')
    def api_add_concept(tid):
        p=request.get_json(silent=True) or {}
        with connect() as db:
            data=validate_concept(db,tid,p)
            cur=db.execute('''INSERT INTO plan_concepto(id_viaje,fecha,tipo,nombre,hora,precio_unitario,cantidad,personas,incluido,nota)
                VALUES (?,?,?,?,?,?,?,?,?,?)''',(tid,)+data)
            return jsonify({'ok':True,'id_concepto':cur.lastrowid}),201

    @app.put('/api/viajes/<int:tid>/plan/conceptos/<int:cid>')
    def api_edit_concept(tid,cid):
        p=request.get_json(silent=True) or {}
        with connect() as db:
            need_trip(db,tid)
            old=rows(db,'SELECT * FROM plan_concepto WHERE id_concepto=? AND id_viaje=?',(cid,tid))
            if not old: raise UserError('Concepto no encontrado.',404)
            data=validate_concept(db,tid,p,old[0])
            db.execute('''UPDATE plan_concepto SET fecha=?,tipo=?,nombre=?,hora=?,precio_unitario=?,cantidad=?,personas=?,incluido=?,nota=?
                WHERE id_concepto=? AND id_viaje=?''',data+(cid,tid))
            return jsonify({'ok':True})

    @app.delete('/api/viajes/<int:tid>/plan/conceptos/<int:cid>')
    def api_del_concept(tid,cid):
        with connect() as db:
            need_trip(db,tid)
            old=rows(db,'SELECT * FROM plan_concepto WHERE id_concepto=? AND id_viaje=?',(cid,tid))
            if not old: raise UserError('Concepto no encontrado.',404)
            if old[0]['automatico']: raise UserError('Las comidas de cada día se pueden editar o marcar como incluidas, no eliminar.')
            db.execute('DELETE FROM plan_concepto WHERE id_concepto=? AND id_viaje=?',(cid,tid))
            return jsonify({'ok':True})

    @app.put('/api/viajes/<int:tid>/plan/config')
    def api_plan_config(tid):
        p=request.get_json(silent=True) or {}
        with connect() as db:
            t=need_trip(db,tid)
            ensure_trip_plan(db,t)
            try:
                pagadores=int(p.get('pagadores'))
                percent=money_value(p.get('reserva_pct'))
            except (ValueError,TypeError) as err: raise UserError(str(err) or 'Configuración inválida.')
            if not 1 <= pagadores <= int(t['num_viajeros']): raise UserError('Los aportantes deben ser entre 1 y el total de viajeros.')
            if percent>50: raise UserError('El margen para imprevistos debe ser 0–50%.')
            db.execute('UPDATE plan_configuracion SET pagadores=?,reserva_pct=? WHERE id_viaje=?',(pagadores,percent,tid))
            return jsonify({'ok':True})

    @app.get('/api/viajes/<int:tid>/plan/pdf')
    def api_plan_pdf(tid):
        # Download is private thanks to session authentication at app.before_request.
        with connect() as db: data=get_plan(db,tid)
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_CENTER
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether
        out=BytesIO()
        pdf=SimpleDocTemplate(out,pagesize=(21*cm,29.7*cm),topMargin=1.8*cm,bottomMargin=1.5*cm,
                              leftMargin=1.8*cm,rightMargin=1.8*cm,title='Itinerario TravelPlanner Flex')
        styles=getSampleStyleSheet()
        styles.add(ParagraphStyle(name='TP_Title',parent=styles['Title'],textColor=colors.HexColor('#15354B'),fontSize=20,leading=24))
        styles.add(ParagraphStyle(name='TP_Sub',parent=styles['Normal'],textColor=colors.HexColor('#566D7C'),spaceAfter=9))
        styles.add(ParagraphStyle(name='TP_H2',parent=styles['Heading2'],textColor=colors.HexColor('#118C83'),spaceBefore=12))
        styles.add(ParagraphStyle(name='TP_Small',parent=styles['Normal'],fontSize=9,leading=13))
        def safe(v): return html_escape(str(v or ''))
        def curr(v): return f'${float(v):,.2f} MXN'
        story=[Paragraph('TravelPlanner Flex | Mi itinerario',styles['TP_Title']),
               Paragraph(safe(data['viaje']['nombre'])+' | '+safe(data['viaje']['destino']),styles['TP_H2']),
               Paragraph(f"{safe(data['viaje']['fecha_inicio'])} al {safe(data['viaje']['fecha_fin'])} · {data['viaje']['num_viajeros']} viajeros · {data['pagadores']} aportantes",styles['TP_Sub'])]
        labels={'alimentacion':'Alimentación','ida_y_regreso':'Boletos de ida y regreso','transporte_local':'Traslados y automóvil','hospedaje':'Hospedaje','actividades':'Actividades','otros':'Otros'}
        for n,day in enumerate(data['dias'],1):
            parts=[Paragraph(f'Día {n} · {safe(day["fecha"])}',styles['TP_H2'])]
            items=[]
            for it in day['conceptos']:
                suffix=' (incluido, $0)' if it['incluido'] else ''
                items.append((TYPE_LABELS.get(it['tipo'],it['tipo'])+' · '+it['nombre']+suffix,it['total']))
            for a in day['actividades']:
                items.append(('Actividad: '+a['nombre'],a['costo_estimado']))
            for h in day['hospedajes']:
                items.append(('Hospedaje: '+h['nombre']+' (estancia total)',h['costo']))
            for tr in day['transportes']:
                items.append(('Transporte: '+tr['origen']+' a '+tr['destino'],tr['costo']))
            if items:
                rows_pdf=[[Paragraph(safe(desc),styles['TP_Small']),Paragraph(curr(value),styles['TP_Small'])] for desc,value in items]
                rows_pdf.append([Paragraph('<b>Subtotal del día</b>',styles['TP_Small']),Paragraph(f'<b>{curr(day["subtotal"])}</b>',styles['TP_Small'])])
                table=Table(rows_pdf,colWidths=[12.7*cm,4.6*cm],hAlign='LEFT')
                table.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),('LINEBELOW',(0,-1),(-1,-1),0.6,colors.HexColor('#A5C9C4')),
                                           ('BOTTOMPADDING',(0,0),(-1,-1),5),('TOPPADDING',(0,0),(-1,-1),5)]))
                parts.append(table)
            else: parts.append(Paragraph('Sin conceptos registrados.',styles['TP_Small']))
            story.extend(parts)
        tbl=[[Paragraph(safe(labels[k]),styles['TP_Small']),Paragraph(curr(v),styles['TP_Small'])] for k,v in data['categorias'].items()]
        tbl += [[Paragraph('<b>Total estimado</b>',styles['TP_Small']),Paragraph(f'<b>{curr(data["subtotal"])}</b>',styles['TP_Small'])],
                [Paragraph(f'Fondo para imprevistos ({data["config"]["reserva_pct"]}%)',styles['TP_Small']),Paragraph(curr(data['fondo_imprevistos']),styles['TP_Small'])],
                [Paragraph('<b>Dinero recomendado</b>',styles['TP_Small']),Paragraph(f'<b>{curr(data["total_recomendado"])}</b>',styles['TP_Small'])],
                [Paragraph(f'Aportación estimada por cada uno de los {data["pagadores"]} aportantes',styles['TP_Small']),Paragraph(curr(data['aporte_por_pagador']),styles['TP_Small'])]]
        table=Table(tbl,colWidths=[12.7*cm,4.6*cm],hAlign='LEFT')
        table.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),('ROWBACKGROUNDS',(0,0),(-1,-1),[colors.white,colors.HexColor('#F2F7F7')]),
                                   ('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7)]))
        story.append(KeepTogether([Paragraph('Resumen económico',styles['TP_H2']),table,Spacer(1,12),
                      Paragraph(f"Gastos realmente registrados: {curr(data['gastado_real'])}. No se suman nuevamente al presupuesto previsto.",styles['TP_Small']),
                      Paragraph('Los importes son estimaciones editables, no cotizaciones ni tarifas confirmadas. Comprueba precios, disponibilidad y traslados.',styles['TP_Small'])]))
        pdf.build(story)
        out.seek(0)
        filename='travelplanner-itinerario-'+str(tid)+'.pdf'
        return send_file(out,mimetype='application/pdf',as_attachment=True,download_name=filename)
