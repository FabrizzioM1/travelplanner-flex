    @app.get('/api/viajes/<int:tid>/plan/pdf')
    def api_plan_pdf(tid):
        # Download is private thanks to session authentication at app.before_request.
        with connect() as db: data=get_plan(db,tid)
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_CENTER
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether
        out=BytesIO()
        pdf=SimpleDocTemplate(out,pagesize=(21*cm,29.7*cm),topMargin=1.8*cm,bottomMargin=1.5*cm,
                              leftMargin=1.8*cm,rightMargin=1.8*cm,title='Itinerario TravelPlanner Flex')
        styles=getSampleStyleSheet()
        styles.add(ParagraphStyle(name='TP_Title',parent=styles['Title'],textColor=colors.HexColor('#15354B'),fontSize=20,leading=24))
        styles.add(ParagraphStyle(name='TP_Sub',parent=styles['Normal'],textColor=colors.HexColor('#566D7C'),spaceAfter=9))
        styles.add(ParagraphStyle(name='TP_H2',parent=styles['Heading2'],textColor=colors.HexColor('#118C83'),spaceBefore=12))
        styles.add(ParagraphStyle(name='TP_Small',parent=styles['Normal'],fontSize=9,leading=13))
        def safe(v): return html_escape(str(v or ''))
        def curr(v): return f'${float(v):,.2f} MXN'
        story=[Paragraph('TravelPlanner Flex | Mi itinerario',styles['TP_Title']),
               Paragraph(safe(data['viaje']['nombre'])+' | '+safe(data['viaje']['destino']),styles['TP_H2']),
               Paragraph(f"{safe(data['viaje']['fecha_inicio'])} al {safe(data['viaje']['fecha_fin'])} · {data['viaje']['num_viajeros']} viajeros · {data['pagadores']} aportantes",styles['TP_Sub'])]
